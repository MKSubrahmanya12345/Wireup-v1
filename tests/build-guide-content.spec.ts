import { expect, test } from '@playwright/test'

const buttonControlId = '14b148218b524bd3886696b661e73954'

test('existing Button Control uses readable connections and honest saved build status', async ({ page, request }) => {
  const before = await (await request.get(`/api/hardware/projects/${buttonControlId}`)).json()
  await page.goto(`/project/${buttonControlId}?section=guide`)
  const guide = page.getByRole('region', { name: 'Interactive Build Guide' })
  await expect(guide.getByRole('progressbar')).toBeVisible({ timeout: 30000 })
  const document = await (await request.get(`/api/hardware/projects/${buttonControlId}/build-guide`)).json()
  expect(document.steps).toHaveLength(8)
  expect(JSON.stringify(document.steps[4].sections)).toContain('INPUT_PULLUP')
  expect(JSON.stringify(document.steps[5].sections)).toContain('Outdated')
  for (const step of document.steps) {
    const prose = JSON.stringify([step.sections, step.instructions, step.checklist.map((check: { display_label: string }) => check.display_label)])
    for (const id of ['button-1', 'led-1', 'r-led', 'wire-button', '14b148']) expect(prose).not.toContain(id)
  }
  expect(await (await request.get(`/api/hardware/projects/${buttonControlId}`)).json()).toEqual(before)
})

for (const width of [1440, 390]) test(`concise Button Control stages preserve progress at ${width}px`, async ({ page, request }, testInfo) => {
  test.setTimeout(180000)
  const original = await (await request.get(`/api/hardware/projects/${buttonControlId}`)).json()
  const project = await (await request.post('/api/hardware/projects', { data: { name: 'Button Control content verification', board: original.board } })).json()
  const command = async (name: string, args: Record<string, unknown>) => {
    const response = await request.post(`/api/hardware/project/${project.id}/command`, { data: { name, args, runtime_token: project.runtime_token } })
    expect(response.ok(), await response.text()).toBe(true)
  }
  for (const part of original.components.filter((part: { id: string }) => part.id !== 'board')) {
    await command('add_component', { ...part, properties: Object.fromEntries(Object.entries(part.properties).filter(([, value]) => value !== null)) })
  }
  for (const wire of original.wires) await command('connect_wire', wire)
  await command('edit_firmware', { source: original.firmware.source })
  const baseline = await (await request.get(`/api/hardware/projects/${project.id}`)).json()
  await page.setViewportSize({ width, height: 1000 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto(`/project/${project.id}?section=guide`)
  const guide = page.getByRole('region', { name: 'Interactive Build Guide' })
  await expect(guide.getByRole('progressbar')).toBeVisible({ timeout: 30000 })
  const steps = guide.getByRole('navigation', { name: 'Build guide steps' }).getByRole('button')
  await expect(steps).toHaveCount(8)
  await expect(guide).toContainText('release it to turn the LED off')
  await guide.getByRole('checkbox').first().click()
  await expect(guide.getByRole('checkbox').first()).toBeChecked()
  await page.reload()
  await expect(guide.getByRole('checkbox').first()).toBeChecked({ timeout: 30000 })
  await steps.nth(1).click()
  await expect(guide).toContainText('220')
  await expect(guide).toContainText('1 × Button')
  await steps.nth(2).click()
  for (const value of ['Arduino Uno pin 2', 'Button pin 1.l', 'Button pin 2.l', 'Arduino Uno pin GND.1', 'Resistor pin 1', 'Resistor pin 2', 'LED pin A', 'LED pin C']) await expect(guide).toContainText(value)
  await expect(guide.getByRole('checkbox')).toHaveCount(5)
  await expect(guide).not.toContainText('wire-button')
  await expect(guide).not.toContainText('button-1')
  await steps.nth(3).click()
  await guide.getByRole('button', { name: 'Run connection checks', exact: true }).click()
  await expect(guide).toContainText('No errors found')
  await guide.locator('summary', { hasText: 'Automatic check details' }).click()
  await expect(guide).toContainText('Automatically verified')
  await steps.nth(4).click()
  await expect(guide).toContainText('INPUT_PULLUP')
  await expect(guide).toContainText('BUTTON_PIN = 2')
  await expect(guide).toContainText('active-low')
  await guide.locator('summary', { hasText: 'View saved sketch' }).click()
  await expect(guide.getByLabel('Saved firmware source')).toContainText(original.firmware.source)
  await steps.nth(5).click()
  await expect(guide).toContainText('Not tested')
  await steps.nth(6).click()
  await expect(guide).toContainText('expect LED off')
  await expect(guide).toContainText('expect LED on')
  await steps.nth(7).click()
  await expect(guide).toContainText('1 of 16 tasks confirmed')
  await expect(guide).toContainText('Next stage: Component preparation')
  await expect(guide).toContainText('Disconnect USB and external power')
  const getGuide = async () => (await (await request.get(`/api/hardware/projects/${project.id}/build-guide`)).json())
  const initialGuide = await getGuide()
  const prepChecks = Object.fromEntries(Object.keys(initialGuide.progress.checks).filter(id => id.startsWith('preparation.')).map(id => [id, true]))
  const response = await request.patch(`/api/hardware/projects/${project.id}/build-guide/progress`, { data: { runtime_token: project.runtime_token, version: initialGuide.version, expected_progress_revision: initialGuide.progress.revision, checks: prepChecks } })
  expect(response.ok()).toBe(true)
  await guide.getByRole('button', { name: 'Reload guide', exact: true }).click()
  await expect(guide).toContainText('Next stage: Wiring')
  expect((await getGuide()).version).toBe(initialGuide.version)
  for (let index = 0; index < 8; index++) {
    await steps.nth(index).click()
    await expect(guide.getByRole('heading', { level: 2 })).toBeVisible()
    const visibleText = await guide.locator('article').innerText()
    for (const id of ['button-1', 'led-1', 'r-led', 'wire-button']) expect(visibleText).not.toContain(id)
    await page.screenshot({ path: testInfo.outputPath(`button-stage-${index + 1}-${width}.png`) })
  }
  expect((await (await request.get(`/api/hardware/projects/${project.id}`)).json()).revision).toBe(baseline.revision)
  const sections = page.getByRole('navigation', { name: 'Project sections' })
  await sections.getByRole('button', { name: 'Code', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Firmware source' })).toHaveValue(original.firmware.source)
  await sections.getByRole('button', { name: 'Wiring / Simulation', exact: true }).click()
  await expect(page.getByLabel('Circuit canvas', { exact: true })).toBeVisible()
  await sections.getByRole('button', { name: 'Info', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Info project details' })).toContainText(original.board)
  await sections.getByRole('button', { name: 'Build Guide', exact: true }).click()
  await expect(guide.getByRole('heading', { level: 2 })).toHaveText('Completion summary')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(await (await request.get(`/api/hardware/projects/${buttonControlId}`)).json()).toEqual(original)
})
