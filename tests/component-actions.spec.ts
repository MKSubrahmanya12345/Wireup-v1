import { expect, test } from '@playwright/test'

for (const width of [1440, 390]) test(`component actions appear only on interaction at ${width}px`, async ({ page, request }) => {
  test.setTimeout(120000)
  const project = await (await request.post('/api/hardware/projects', { data: { name: 'Transient component actions', board: 'arduino-uno' } })).json()
  await request.post(`/api/hardware/project/${project.id}/command`, { data: { name: 'add_component', args: { type: 'led', id: 'led', x: 480, y: 250 } } })
  await page.setViewportSize({ width, height: 1000 })
  await page.goto(`/project/${project.id}`)
  const actions = page.locator('.hw-part-actions')
  const board = page.getByRole('button', { name: 'Select board', exact: true })
  await expect(board).toBeVisible({ timeout: 30000 })
  await expect(actions).toHaveCount(0)
  await page.getByRole('button', { name: 'Fit circuit', exact: true }).click()
  await board.hover()
  await expect(page.getByRole('toolbar', { name: 'Actions for board' })).toBeVisible()
  await page.getByRole('button', { name: 'Rotate board', exact: true }).hover()
  await expect(actions).toHaveCount(1)
  await page.mouse.move(1, 1)
  await expect(actions).toHaveCount(0)
  await board.click()
  await page.mouse.move(1, 1)
  await expect(actions).toHaveCount(1)
  const viewport = page.getByLabel('Circuit canvas', { exact: true })
  const box = await viewport.boundingBox()
  await page.mouse.click(box!.x + box!.width - 20, box!.y + box!.height - 80)
  await expect(actions).toHaveCount(0)
  await board.focus()
  await expect(actions).toHaveCount(1)
  await board.press('Escape')
  await expect(actions).toHaveCount(0)
  const led = page.getByRole('button', { name: 'Select led', exact: true })
  await led.hover()
  await expect(page.getByRole('toolbar', { name: 'Actions for led' })).toBeVisible()
  await page.getByRole('button', { name: 'Rotate led', exact: true }).click()
  await expect.poll(async () => {
    const state = await (await request.get(`/api/hardware/projects/${project.id}`)).json()
    return state.components.find((part: { id: string }) => part.id === 'led').rotation
  }).toBe(90)
  await page.reload()
  await expect(board).toBeVisible({ timeout: 30000 })
  await page.mouse.move(1, 1)
  await expect(actions).toHaveCount(0)
})
