import { expect, test } from '@playwright/test'

for (const width of [1440, 390]) test(`Example strip moves and opens cards at ${width}px`, async ({ page, request }) => {
 const catalog = await (await request.get('/api/hardware/samples/all')).json()
 await page.setViewportSize({ width, height: 900 })
 await page.goto('/')
 const region = page.getByRole('region', { name: 'Scrolling starter examples' })
 await expect(region).toBeVisible()
 const track = region.locator('.sample-strip-track')
 const position = () => track.evaluate(element => getComputedStyle(element).transform)
 const initial = await position()
 await expect.poll(position).not.toBe(initial)
 const cards = region.locator('.sample-strip-group').first().getByRole('button')
 const tops = await cards.evaluateAll(elements => elements.map(element => element.getBoundingClientRect().top))
 expect(Math.max(...tops) - Math.min(...tops)).toBeLessThan(2)
 await expect(page.getByRole('button', { name: 'Pause scrolling', exact: true })).toHaveCount(0)
 await expect(cards).toHaveCount(catalog.examples.filter((example: { available: boolean }) => example.available).length)
 const bounds = await region.boundingBox()
 expect(bounds!.x).toBeCloseTo(0, 0)
 expect(bounds!.width).toBeCloseTo(width, 0)
 await expect(region).toHaveCSS('scrollbar-width', 'none')
 await region.hover()
 await expect(track).toHaveCSS('animation-play-state', 'paused')
 await region.focus()
 await expect(track).toHaveCSS('animation-play-state', 'paused')
 await cards.first().focus()
 await expect(cards.first()).toBeFocused()
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
 await page.screenshot({ path: `test-results/example-strip-${width}.png`, fullPage: true })
 await cards.first().press('Enter')
 await expect(page).toHaveURL(/\/project\//, { timeout: 30000 })
 await expect(page.getByRole('button', { name: 'Info', exact: true })).toBeVisible({ timeout: 30000 })
 await page.goto('/')
 await page.getByRole('link', { name: 'View all examples' }).click()
 await expect(page).toHaveURL(/\/examples$/)
 await expect(page.getByRole('heading', { name: 'Example projects' }).first()).toBeVisible()
})

test('Reduced motion and starter error states remain usable', async ({ page }) => {
 await page.emulateMedia({ reducedMotion: 'reduce' })
 await page.goto('/')
 const region = page.getByRole('region', { name: 'Scrolling starter examples' })
 await expect(region).toBeVisible()
 await expect(region.locator('.sample-strip-track')).toHaveCSS('animation-name', 'none')
 await expect(page.getByRole('button', { name: 'Pause scrolling' })).toBeHidden()
 await expect(region.locator('.sample-strip-duplicate')).toBeHidden()
 await region.locator('.sample-strip-group').first().getByRole('button').last().focus()
 await expect(region.locator('.sample-strip-group').first().getByRole('button').last()).toBeInViewport()
 await page.route('**/api/hardware/samples/all', route => route.fulfill({ status: 503 }))
 await page.reload(); await expect(page.getByRole('alert')).toContainText('Starter projects are temporarily unavailable')
 await page.unroute('**/api/hardware/samples/all')
 await page.route('**/api/hardware/samples/all', route => route.fulfill({ json: { examples: [] } }))
 await page.reload(); await expect(page.getByRole('region', { name: 'Starter projects' })).toContainText('No compatible starters')
 await expect(page.getByRole('region', { name: 'Scrolling starter examples' })).toHaveCount(0)
})
