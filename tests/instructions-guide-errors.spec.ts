import { expect, test } from '@playwright/test'
test.use({ reducedMotion: 'reduce' })
test.setTimeout(120_000)
test('Actual Button Control instructions and failed completion stay honest', async ({ page, request }) => {
 const originalId = '14b148218b524bd3886696b661e73954'
 const response = await request.get(`/api/hardware/projects/${originalId}`)
 test.skip(!response.ok(), 'Actual Button Control project is unavailable')
 const original = await response.json()
 await page.goto(`/project/${originalId}`)
 await page.getByRole('button', { name: 'Project details', exact: true }).click(); await page.getByRole('button', { name: 'Instructions', exact: true }).click()
 const ui = page.locator('.instructions-guide')
 await expect(ui).toContainText('Button Control build instructions')
 await expect(ui).toContainText('Connect Arduino Uno pin 2 to Pushbutton pin 1.l')
 await ui.getByRole('button', { name: /Bring-up/ }).press('Enter')
 await ui.locator('.ig-card').filter({ hasText: 'Review the saved firmware' }).getByRole('button', { name: 'View details' }).click()
 await expect(ui).toContainText('INPUT_PULLUP')
 await expect(ui).toContainText('BUTTON_PIN')
 await page.screenshot({ path: 'test-results/instructions-button-control.png', fullPage: true })
 const after = await (await request.get(`/api/hardware/projects/${originalId}`)).json()
 expect(after.revision).toBe(original.revision); expect(after.firmware).toEqual(original.firmware)
 const project = await (await request.post('/api/hardware/projects', { data: { name: 'Failed completion', board: 'arduino-uno' } })).json()
 await page.goto(`/project/${project.id}`)
 await page.getByRole('button', { name: 'Project details', exact: true }).click(); await page.getByRole('button', { name: 'Instructions', exact: true }).click()
 await expect(ui.locator('.ig-card').first()).toBeVisible()
 await page.route(`**/projects/${project.id}/build-guide/progress`, route => route.fulfill({ status: 409, json: { detail: 'Progress changed elsewhere' } }))
 await ui.getByRole('checkbox').first().click()
 await expect(ui.getByRole('alert')).toContainText('changed elsewhere')
 await expect(ui.getByRole('checkbox').first()).not.toBeChecked()
 await ui.getByRole('button', { name: 'Retry loading instructions' }).click()
 await expect(ui.getByRole('alert')).toHaveCount(0)
 await expect(ui.getByRole('checkbox').first()).not.toBeChecked()
 await request.delete(`/api/hardware/projects/${project.id}`)
})
