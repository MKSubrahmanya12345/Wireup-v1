import {expect,test} from '@playwright/test'
import fs from 'node:fs'
for(const width of [1440,390])test(`structured project views stay synchronized at ${width}px`,async({page,request})=>{
 const project=await(await request.post('/api/hardware/projects',{data:{name:'Blueprint comparison',board:'arduino-uno'}})).json()
 const command=async(name:string,args:Record<string,unknown>)=>{const result=await request.post(`/api/hardware/project/${project.id}/command`,{data:{name,args}});expect(result.ok()).toBe(true)}
 await command('add_component',{type:'led',id:'led',x:420,y:150})
 await command('connect_wire',{from:{component:'board',pin:'13'},to:{component:'led',pin:'A'}})
 await page.setViewportSize({width,height:900});await page.goto(`/project/${project.id}`)
 await page.getByRole('button',{name:'Project details',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'Blueprint comparison'})
 await expect(dialog).toBeVisible()
 await expect(dialog.getByRole('region',{name:'Info project details'})).toContainText('Not compiled')
 await dialog.getByRole('button',{name:'Parts',exact:true}).click()
 await expect(dialog).toContainText('led');await expect(dialog).toContainText('Qty')
 await dialog.getByRole('button',{name:'Wiring',exact:true}).click()
 await expect(dialog).toContainText('board · 13');await expect(dialog).toContainText('led · A')
 await dialog.getByRole('searchbox').fill('missing-pin');await expect(dialog).toContainText('No connections match')
 await dialog.getByRole('searchbox').fill('')
 await dialog.getByRole('button',{name:'Instructions',exact:true}).click()
 await dialog.locator('.ig-card').filter({hasText:'Connect Arduino Uno pin 13'}).getByRole('button',{name:'View details'}).click()
 await expect(dialog).toContainText('board · 13');await expect(dialog).toContainText('not automatically completed')
 const downloaded=page.waitForEvent('download');await dialog.getByRole('button',{name:'Export JSON backup'}).click()
 const file=await(await downloaded).path();const backup=JSON.parse(fs.readFileSync(file!,'utf8'))
 expect(backup.components.length).toBe(2);expect(backup.wires[0].from.pin).toBe('13');expect(JSON.stringify(backup)).not.toContain('runtime_token')
 await dialog.getByRole('button',{name:'Close project details'}).click()
 await command('add_component',{type:'resistor',id:'resistor'})
 await page.reload();await page.getByRole('button',{name:'Project details',exact:true}).click()
 await dialog.getByRole('button',{name:'Parts',exact:true}).click();await expect(dialog).toContainText('resistor')
 await page.keyboard.press('Escape');await expect(dialog).toHaveCount(0)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
