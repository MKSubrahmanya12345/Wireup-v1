import {expect,test} from '@playwright/test'
for(const width of [1440,390])test(`assistant text stays inside padded card and composer at ${width}px`,async({page,request})=>{
 const project=await(await request.post('/api/hardware/projects',{data:{name:'Chat readability',board:'arduino-uno'}})).json()
 await page.setViewportSize({width,height:900})
 await page.route('**/api/health',route=>route.fulfill({json:{configured:true,model:'test'}}))
 await page.route('**/api/chat',route=>route.fulfill({contentType:'application/x-ndjson',body:JSON.stringify({type:'text',channel:'answer',text:'## Welcome to your project\n\nReadable instructions.\n\n1. Open Sketch.\n2. Compile the actual firmware.\n\n'+('Additional project details.\n\n'.repeat(15))})+'\n'+JSON.stringify({type:'done'})+'\n'}))
 await page.goto(`/project/${project.id}`)
 if(width<900)await page.getByRole('button',{name:'Agent',exact:true}).click()
 await page.getByRole('textbox',{name:'Message WireUp'}).fill('Explain this project')
 await page.getByRole('button',{name:'Send message',exact:true}).click()
 const card=page.locator('.wireup-assistant-message').last()
 await expect(card).toContainText('Readable instructions.',{timeout:20000})
 expect(await card.evaluate(el=>getComputedStyle(el).paddingLeft)).toBe('14px')
 expect(await card.locator('h2').evaluate(el=>getComputedStyle(el).fontSize)).toBe('13px')
 expect(await card.locator('h2').evaluate(el=>getComputedStyle(el).textTransform)).toBe('none')
 const input=page.getByRole('textbox',{name:'Message WireUp'});await expect(input).toBeVisible()
 await page.getByRole('log',{name:'Conversation'}).evaluate(el=>{el.scrollTop=el.scrollHeight})
 await input.fill('Follow up');await expect(page.getByRole('button',{name:'Send message',exact:true})).toBeEnabled()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
