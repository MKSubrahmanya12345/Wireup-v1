import { expect, test } from '@playwright/test'
test.use({ reducedMotion: 'reduce' })
test.setTimeout(90_000)
for (const width of [1440, 390]) test(`Cream grid and compact full-width header at ${width}px`, async ({ page, request }) => {
 await page.setViewportSize({ width, height: 900 })
 await page.goto('/')
 const header = page.locator('.home-grid-intro > header')
 await expect(header).toBeVisible()
 await expect(header).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
 await expect(header).toHaveCSS('backdrop-filter', 'none')
 await expect(header).toHaveCSS('border-bottom-width', '0px')
 const bounds = await header.boundingBox()
 expect(bounds!.height).toBe(56); expect(bounds!.width).toBe(width)
 await expect(page.locator('.nova-home')).toHaveCSS('background-color', 'rgb(252, 240, 218)')
 await expect(page.locator('.nova-home')).toHaveCSS('background-image', 'none')
 expect(await page.locator('.home-grid-intro').evaluate(e => getComputedStyle(e).backgroundImage)).toContain('linear-gradient')
 await expect(page.locator('.home-grid-intro')).toHaveCSS('background-size', '100px 100px, 100px 100px, 20px 20px, 20px 20px')
 await expect(page.locator('.nova-home main')).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
 await expect(page.getByRole('heading', { name: 'What do you want to build?' })).toBeVisible()
 await expect(page.locator('.home-workbench-art')).toHaveAttribute('aria-hidden', 'true')
 await expect(page.locator('.home-board img')).toHaveCount(2)
 await expect.poll(() => page.locator('.home-board img').evaluateAll(images => images.every(image => (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth > 0))).toBe(true)
 await expect(page.locator('form')).toHaveCSS('background-color', 'rgb(36, 36, 36)')
 await expect(page.locator('form textarea')).toHaveCSS('color', 'rgb(238, 238, 238)')
 await expect(page.getByRole('button', { name: 'Build prototype', exact: true })).toBeDisabled()
 await page.getByRole('button', { name: 'Blink an LED with Arduino', exact: true }).click()
 await expect(page.locator('form textarea')).toHaveValue('Blink an LED with Arduino')
 await expect(page.getByRole('button', { name: 'Build prototype', exact: true })).toBeEnabled()
 const button = await header.getByRole('button', { name: 'New prototype' }).boundingBox()
 expect(button!.y).toBeGreaterThanOrEqual(bounds!.y)
 expect(button!.y + button!.height).toBeLessThanOrEqual(bounds!.y + bounds!.height)
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
 const how = page.getByRole('region', { name: 'How WireUp Works', exact: true })
 await how.scrollIntoViewIfNeeded()
 await expect(how).toHaveCSS('background-color', 'rgb(174, 172, 120)')
 await expect(how.getByRole('listitem')).toHaveCount(4)
 for (const title of ['Describe your idea', 'AI Generation', 'Refine & Iterate', 'Build Faster']) await expect(how.getByRole('heading', { name: title, exact: true })).toBeVisible()
 const cards = await how.getByRole('listitem').evaluateAll(items => items.map(e => ({ x: e.getBoundingClientRect().x, y: e.getBoundingClientRect().y, right: e.getBoundingClientRect().right })))
 expect(cards.every(card => card.x >= 0 && card.right <= width)).toBe(true)
 if (width === 1440) expect(new Set(cards.map(card => card.y)).size).toBe(1)
 else expect(new Set(cards.map(card => card.y)).size).toBe(4)
 await page.screenshot({ path: `test-results/home-how-${width}.png`, fullPage: true })
 await page.getByRole('textbox', { name: 'Describe your hardware prototype' }).click()
 await expect(page.locator('form textarea')).toHaveCSS('outline-style', 'none')
 await expect(page.locator('form')).toHaveCSS('border-color', 'rgb(136, 136, 136)')
 await page.getByRole('textbox', { name: 'Describe your hardware prototype' }).fill('Home prompt browser verification')
 await page.getByRole('button', { name: 'Build prototype', exact: true }).click()
 await expect(page).toHaveURL(/\/project\/[a-z0-9]+$/, { timeout: 30_000 })
 const id = page.url().split('/').pop()!
 try {
  await expect(page.getByRole('region', { name: 'Circuit canvas' })).toBeVisible({ timeout: 30_000 })
  await page.getByRole('link', { name: 'WireUp home', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
  await page.getByRole('link', { name: 'View all examples' }).click()
  await expect(page).toHaveURL(/\/examples$/)
  await expect(page.getByRole('heading', { name: 'Example projects', exact: true })).toBeVisible()
 } finally { await request.delete(`/api/hardware/projects/${id}`) }
})
