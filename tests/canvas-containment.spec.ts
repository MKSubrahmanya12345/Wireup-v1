import { expect, test } from '@playwright/test'
import { canvasBounds, containPartPosition } from '../src/hardware/canvas-bounds'
import { roundedOrthogonalPath, routeWirePaths } from '../src/hardware/wire-path'
test.use({ reducedMotion: 'reduce' })
test.setTimeout(120_000)
test.use({ actionTimeout: 30_000 })
test('Canvas bounds include rotated parts, negative coordinates, and routed wires', () => {
 const part = { id: 'rotated', type: 'servo', x: -100, y: -50, rotation: 90, properties: {} }
 const extent = canvasBounds([part], { rotated: { width: 220, height: 70 } }, ['M -140 -80 L 1500 900'])
 expect(extent.offsetX).toBeGreaterThan(140); expect(extent.offsetY).toBeGreaterThan(80)
 expect(extent.width).toBeGreaterThan(1500); expect(extent.height).toBeGreaterThan(900)
 const safe = containPartPosition(part, { width: 220, height: 70 }, { x: -900, y: -900 })
 expect(safe.x).toBeGreaterThan(70); expect(safe.y).toBeGreaterThan(20)
})
test('Cable simplification preserves reversals at endpoint leads', () => {
 expect(roundedOrthogonalPath([{ x: 0, y: 0 }, { x: 18, y: 0 }, { x: -118, y: 0 }, { x: -100, y: 0 }])).toBe('M 0 0 L 18 0 L -118 0 L -100 0')
})
test('Cable routing can detour around obstacles beyond the old canvas edges', () => {
 const paths = routeWirePaths([{ id: 'outside', start: { component: 'a', x: -100, y: 800, direction: { x: 1, y: 0 } }, end: { component: 'b', x: 1400, y: 800, direction: { x: -1, y: 0 } } }], [{ id: 'obstacle', left: 200, right: 900, top: -100, bottom: 1000 }])
 const path = paths.get('outside')!
 expect(path.startsWith('M -100 800')).toBe(true)
 const coordinates = [...path.matchAll(/-?\d+(?:\.\d+)?/g)].map(match => Number(match[0]))
 const ys = coordinates.filter((_, index) => index % 2 === 1)
 expect(ys.some(y => y <= -118 || y >= 1018)).toBe(true)
 expect(path.endsWith('L 1400 800')).toBe(true)
})
