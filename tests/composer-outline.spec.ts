import { expect, test } from '@playwright/test'

for (const width of [1440, 390]) test(`composer controls have no inner outlines at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 })
  await page.route('**/api/health', route => route.fulfill({ json: { configured: true, model: 'fixture', providers: [{ id: 'groq', label: 'Groq', model: 'fixture', configured: true }, { id: 'azure', label: 'Azure', model: 'fixture', configured: true }] } }))
  await page.route('**/api/chat', route => route.fulfill({ contentType: 'application/x-ndjson', body: '{"type":"text","channel":"answer","text":"Ready."}\n{"type":"done","status":"success"}\n' }))
  await page.goto('/assistant', { waitUntil: 'domcontentloaded' })
  await page.getByRole('textbox', { name: 'Message WireUp' }).fill('Open conversation')
  await page.getByRole('button', { name: 'Send message', exact: true }).click()
  await expect(page.getByText('Ready.', { exact: true })).toBeVisible()
  const input = page.locator('.wireup-aui__input')
  await input.click()
  await input.fill('Follow-up')
  await expect(input).toHaveCSS('outline-style', 'none')
  await expect(input).toHaveCSS('border-top-width', '0px')
  await expect(input).toHaveCSS('box-shadow', 'none')
  const model = page.getByRole('combobox', { name: 'AI model provider' })
  await model.focus()
  await expect(model).toHaveCSS('outline-style', 'none')
  await expect(model).toHaveCSS('border-top-width', '0px')
  await expect(model).toHaveCSS('box-shadow', 'none')
  await model.selectOption('azure::fixture')
  await expect(model).toHaveValue('azure::fixture')
  await page.screenshot({ path: `test-results/composer-clean-${width}.png` })
  await page.getByRole('button', { name: 'Send message', exact: true }).click()
  await expect(page.getByText('Ready.', { exact: true })).toHaveCount(2)
})
