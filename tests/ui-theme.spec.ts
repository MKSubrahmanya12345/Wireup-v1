import {expect,test} from '@playwright/test'
for(const width of [1440,390])test(`reference theme preserves app flows at ${width}px`,async({page,request})=>{
 test.setTimeout(120000)
 await page.setViewportSize({width,height:900})
 await page.route('**/api/health',route=>route.fulfill({json:{configured:true,model:'test'}}))
 await page.route('**/api/chat',route=>route.fulfill({contentType:'application/x-ndjson',body:JSON.stringify({type:'text',channel:'answer',text:'UI verification response.'})+'\n'+JSON.stringify({type:'done'})+'\n'}))
 await page.goto('/')
 expect(await page.locator('.nova-home').evaluate(el=>getComputedStyle(el).backgroundColor)).toBe('rgb(22, 22, 22)')
 for(const route of ['/projects','/examples','/assistant']){
  await page.goto(route);await expect(page.locator('h1').first()).toBeVisible();expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 }
 const project=await(await request.post('/api/hardware/projects',{data:{name:'Theme workspace',board:'arduino-uno'}})).json()
 await request.post(`/api/hardware/project/${project.id}/command`,{data:{name:'add_component',args:{type:'led',id:'led',x:430,y:160}}})
 await request.post(`/api/hardware/project/${project.id}/command`,{data:{name:'connect_wire',args:{from:{component:'board',pin:'13'},to:{component:'led',pin:'A'}}}})
 await page.goto(`/project/${project.id}`)
 await expect(page.getByLabel('Circuit canvas',{exact:true})).toBeVisible({timeout:30000})
 expect(await page.locator('.hw-header').evaluate(el=>getComputedStyle(el).backgroundColor)).toBe('rgb(28, 28, 28)')
 expect(await page.locator('.hw-canvas-viewport').evaluate(el=>getComputedStyle(el).backgroundColor)).toBe('rgb(212, 209, 201)')
 expect(await page.locator('.hw-canvas-viewport').evaluate(el=>getComputedStyle(el).backgroundImage)).toContain('linear-gradient')
 await expect(page.locator('wokwi-arduino-uno')).toBeVisible()
 if(width<900)await page.getByRole('button',{name:'Agent',exact:true}).click()
 await page.getByRole('textbox',{name:'Message WireUp'}).fill('Hello theme')
 await page.getByRole('button',{name:'Send message',exact:true}).click()
 await expect(page.getByText('UI verification response.',{exact:false})).toBeVisible({timeout:20000})
 if(width<900)await page.getByRole('button',{name:'Canvas',exact:true}).click()
 await page.getByRole('button',{name:'Sketch',exact:true}).click();await expect(page.getByRole('dialog')).toBeVisible();await page.keyboard.press('Escape')
 await page.getByRole('tab',{name:'Schematic',exact:true}).click();await expect(page.getByRole('region',{name:'Schematic view',exact:true})).toBeVisible()
 await page.getByRole('tab',{name:'Circuit',exact:true}).click()
 if(width<900)await page.getByRole('button',{name:'Canvas',exact:true}).click()
 const wire=page.getByRole('button',{name:'Inspect wire board.13 to led.A',exact:true});await wire.focus();await wire.press('Enter');await expect(page.getByRole('dialog',{name:'Wire connection details'})).toContainText('Pin 13')
 await page.getByRole('button',{name:'Close wire details'}).click()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:`test-results/nova-theme-${width}.png`})
})
