import { expect as baseExpect, test } from '@playwright/test'

const expect = baseExpect.configure({ timeout: 30000 })

for (const width of [1440, 390]) test(`build guide saves explicit progress and flags changed source at ${width}px`, async ({ page, request }, testInfo) => {
  test.setTimeout(300000)
  const project = await (await request.post('/api/hardware/projects', { data: { name: 'Guide continuity', board: 'arduino-uno' } })).json()
  const command = async (name: string, args: Record<string, unknown>) => {
    const response = await request.post(`/api/hardware/project/${project.id}/command`, { data: { name, args } })
    expect(response.ok()).toBe(true)
    return response.json()
  }
  await command('add_component', { type: 'resistor', id: 'r', properties: { value: '220' }, x: 460, y: 160 })
  await command('add_component', { type: 'led', id: 'led', x: 560, y: 160 })
  for (const [from, to] of [
    [{ component: 'board', pin: '13' }, { component: 'r', pin: '1' }],
    [{ component: 'r', pin: '2' }, { component: 'led', pin: 'A' }],
    [{ component: 'led', pin: 'C' }, { component: 'board', pin: 'GND' }],
  ]) await command('connect_wire', { from, to })
  const initial = await (await request.get(`/api/hardware/projects/${project.id}`)).json()
  await page.setViewportSize({ width, height: 1000 })
  await page.goto(`/project/${project.id}?section=guide`)
  const guide = page.getByRole('region', { name: 'Interactive Build Guide' })
  await expect(guide.getByRole('progressbar')).toBeVisible({ timeout: 30000 })
  await page.evaluate(() => document.fonts.ready)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const steps = guide.getByRole('navigation', { name: 'Build guide steps' }).getByRole('button')
  await expect(steps).toHaveCount(8)
  const progressBefore = await guide.getByRole('progressbar').getAttribute('aria-valuenow')
  await guide.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(guide.getByRole('progressbar')).toHaveAttribute('aria-valuenow', progressBefore!)
  await expect(guide).toContainText('220')
  await guide.getByRole('checkbox').first().click()
  await expect(guide.getByRole('checkbox').first()).toBeChecked()
  await page.reload()
  await expect(guide.getByRole('checkbox').first()).toBeChecked({ timeout: 30000 })
  const stored = await (await request.get(`/api/hardware/projects/${project.id}`)).json()
  expect(stored.revision).toBe(initial.revision)
  expect(stored.firmware).toEqual(initial.firmware)
  await steps.nth(2).click()
  await expect(guide).toContainText('13')
  await expect(guide).toContainText('GND.1')
  await guide.getByRole('checkbox').first().click()
  await steps.nth(3).click()
  await guide.getByRole('button', { name: 'Run connection checks', exact: true }).click()
  await expect(guide).toContainText('No errors found')
  await guide.locator('summary', { hasText: 'Automatic check details' }).click()
  await expect(guide).toContainText('Automatically verified')
  await expect(guide).toContainText('physical')
  await steps.nth(5).click()
  await guide.getByRole('button', { name: 'Verify compilation evidence', exact: true }).click()
  await guide.locator('summary', { hasText: 'Automatic check details' }).click()
  await expect(guide).toContainText('No actual current successful artifact')
  await guide.getByRole('button', { name: 'Compile firmware', exact: true }).click()
  await expect(guide.getByRole('button', { name: 'Run simulation', exact: true })).toBeEnabled({ timeout: 90000 })
  await guide.getByRole('button', { name: 'Verify compilation evidence', exact: true }).click()
  await expect(guide).toContainText('Current successful saved artifact verified')
  await guide.getByRole('button', { name: 'Run simulation', exact: true }).click()
  await expect(guide.getByRole('button', { name: 'Stop simulation', exact: true })).toBeEnabled({ timeout: 30000 })
  const sections = page.getByRole('navigation', { name: 'Project sections' })
  await guide.getByRole('button', { name: 'Open Wiring', exact: true }).click()
  await expect(sections.getByRole('button', { name: 'Wiring / Simulation', exact: true })).toHaveAttribute('aria-pressed', 'true', { timeout: 15000 })
  await page.getByRole('button', { name: 'Simulation', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Stop', exact: true })).toBeVisible()
  await sections.getByRole('button', { name: 'Build Guide', exact: true }).press('Enter')
  await guide.getByRole('button', { name: 'Stop simulation', exact: true }).click()
  await expect(guide.getByRole('button', { name: 'Run simulation', exact: true })).toBeEnabled()
  await guide.getByRole('button', { name: 'Verify simulation evidence', exact: true }).click()
  await expect(guide).toContainText('no automatic behavior verifier is available')
  await guide.getByRole('checkbox').first().click()
  await guide.getByRole('checkbox').nth(1).click()
  await steps.nth(4).click()
  await guide.getByRole('checkbox').first().click()
  await sections.getByRole('button', { name: 'Code', exact: true }).press('Enter')
  await page.getByRole('textbox', { name: 'Firmware source' }).fill('void setup() { pinMode(13, OUTPUT); }\nvoid loop() { digitalWrite(13, HIGH); }')
  await sections.getByRole('button', { name: 'Build Guide', exact: true }).press('Enter')
  await expect(guide).toContainText('Unsaved')
  await sections.getByRole('button', { name: 'Code', exact: true }).press('Enter')
  await page.getByRole('button', { name: 'Save sketch', exact: true }).click()
  await expect.poll(async () => (await (await request.get(`/api/hardware/projects/${project.id}`)).json()).firmware.source).toContain('digitalWrite(13, HIGH)')
  await sections.getByRole('button', { name: 'Build Guide', exact: true }).press('Enter')
  await expect(guide).toContainText('Outdated')
  await steps.nth(1).click()
  await expect(guide.getByRole('checkbox').first()).toBeChecked()
  await steps.nth(2).click()
  await expect(guide.getByRole('checkbox').first()).toBeChecked()
  await steps.nth(5).click()
  await expect(guide.getByRole('checkbox').first()).not.toBeChecked()
  await guide.getByRole('checkbox').first().click()
  await expect(guide.getByRole('checkbox').first()).toBeChecked()
  await expect(guide.getByRole('checkbox').nth(1)).not.toBeChecked()
  await guide.getByRole('checkbox').nth(1).click()
  await expect(guide.getByRole('checkbox').first()).toBeChecked()
  await expect(guide.getByRole('checkbox').nth(1)).toBeChecked()
  await command('modify_component', { id: 'led', x: 610, y: 220, rotation: 90 })
  await page.reload()
  await steps.nth(2).click()
  await expect(guide.getByRole('checkbox').first()).toBeChecked()
  await command('modify_component', { id: 'r', properties: { value: '330' } })
  await page.reload()
  await expect(guide.getByRole('checkbox').first()).not.toBeChecked({ timeout: 30000 })
  await expect(guide).toContainText('Outdated')
  await steps.nth(1).click()
  await expect(guide).toContainText('330')
  await expect(guide.getByRole('checkbox').first()).not.toBeChecked()
  await sections.getByRole('button', { name: 'Info', exact: true }).press('Enter')
  await expect(page.getByRole('region', { name: 'Info project details' })).toContainText('Firmware revision2')
  await sections.getByRole('button', { name: 'Wiring / Simulation', exact: true }).press('Enter')
  await expect(page.getByLabel('Circuit canvas', { exact: true })).toBeVisible()
  if (width < 600) {
    await page.getByRole('navigation', { name: 'Workspace panels' }).getByRole('button', { name: 'Parts', exact: true }).click()
    await expect(page.getByRole('textbox', { name: 'Search components' })).toBeVisible()
    await page.getByRole('navigation', { name: 'Workspace panels' }).getByRole('button', { name: 'Canvas', exact: true }).click()
  }
  await sections.getByRole('button', { name: 'Build Guide', exact: true }).press('Enter')
  for (let index = 0; index < 8; index++) { await steps.nth(index).click(); await expect(guide.getByRole('heading', { level: 2 })).toBeVisible() }
  await page.screenshot({ path: testInfo.outputPath(`build-guide-${width}.png`) })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

for (const width of [1440, 390]) test(`empty guide and service failure remain explicit at ${width}px`, async ({ page, request }) => {
  const project = await (await request.post('/api/hardware/projects', { data: { name: 'Empty guide' } })).json()
  await page.setViewportSize({ width, height: 900 })
  await page.goto(`/project/${project.id}?section=guide`)
  const guide = page.getByRole('region', { name: 'Interactive Build Guide' })
  await expect(guide.getByRole('progressbar')).toBeVisible({ timeout: 30000 })
  await expect(guide).toContainText('No parts saved')
  await guide.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(guide).toContainText('Add the parts needed for your goal')
  await guide.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(guide).toContainText('no wires are saved')
  const steps = guide.getByRole('navigation', { name: 'Build guide steps' }).getByRole('button')
  await steps.nth(5).click()
  await expect(guide.getByRole('button', { name: 'Compile firmware', exact: true })).toBeDisabled()
  await expect(guide.getByRole('button', { name: 'Run simulation', exact: true })).toBeDisabled()
  await page.route(`**/api/hardware/projects/${project.id}/build-guide`, route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: 'Guide service temporarily unavailable' }) }))
  await guide.getByRole('button', { name: 'Reload guide', exact: true }).click()
  await expect(guide.getByRole('alert')).toContainText('Guide service temporarily unavailable')
  await page.unroute(`**/api/hardware/projects/${project.id}/build-guide`)
  await guide.getByRole('button', { name: 'Reload latest progress', exact: true }).click()
  await expect(guide.getByRole('alert')).toHaveCount(0)
  await expect(guide.getByRole('progressbar')).toHaveAttribute('aria-valuenow', '0')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
