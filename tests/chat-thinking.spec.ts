import { expect, test } from '@playwright/test'
for (const width of [1440, 390]) test(`thinking gears and bottom composer at ${width}px`, async ({ page, request }) => {
 const project = await (await request.post('/api/hardware/projects', { data: { name: 'Thinking verification' } })).json()
 await page.setViewportSize({ width, height: 900 })
 await page.route('**/api/health', route => route.fulfill({ json: { configured: true, model: 'gpt-6.1-sol', providers: [{ id: 'azure', label: 'Azure', model: 'gpt-6.1-sol', configured: true }] } }))
 await page.addInitScript(() => {
  const original = window.fetch.bind(window)
  window.fetch = (input, init) => input === '/api/chat' ? Promise.resolve(new Response(new ReadableStream({ start(controller) { init?.signal?.addEventListener('abort', () => controller.error(new DOMException('Aborted', 'AbortError')), { once: true }) } }))) : original(input, init)
 })
 try {
  await page.goto(`/project/${project.id}`, { waitUntil: 'domcontentloaded' })
  if (width === 390) await page.getByRole('button', { name: 'Agent', exact: true }).click()
  await page.getByRole('textbox', { name: 'Message WireUp' }).fill('Check my project')
  await page.getByRole('button', { name: 'Send message', exact: true }).click()
  const thinking = page.locator('.wireup-aui__thinking')
  await expect(thinking).toBeVisible()
  await expect(thinking).toContainText('Thinking')
  await expect(thinking.locator('img')).toHaveCount(3)
  await expect(thinking.locator('img').first()).toHaveCSS('animation-name', 'aui-gear-turn')
  await expect(page.getByText('AI can make mistakes. Check wiring and real test results.', { exact: true })).toHaveCount(0)
  await expect(page.locator('.wireup-aui__stop-note')).toHaveCount(0)
  await expect(page.locator('.wireup-aui__composer')).toHaveCSS('border-radius', '6px')
  const footer = await page.locator('.wireup-aui__footer').boundingBox()
  const composer = await page.locator('.wireup-aui__composer').boundingBox()
  expect(Math.abs(footer!.y + footer!.height - composer!.y - composer!.height)).toBeLessThan(2)
  await page.screenshot({ path: `test-results/thinking-${width}.png` })
  await page.getByRole('button', { name: 'Stop generation', exact: true }).click()
  await expect(thinking).toHaveCount(0)
  await expect(page.getByText('Interrupted', { exact: true })).toBeVisible()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByRole('button', { name: 'Retry', exact: true }).click()
  await expect(thinking.locator('img').first()).toHaveCSS('animation-name', 'none')
  await page.getByRole('button', { name: 'Stop generation', exact: true }).click()
 } finally { await page.goto('/', { waitUntil: 'domcontentloaded' }); await request.delete(`/api/hardware/projects/${project.id}`) }
})
