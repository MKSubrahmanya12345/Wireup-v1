import {expect,test} from '@playwright/test'
for(const width of [1440,390])test(`board dots and actual breadboard routing preserve connectivity at ${width}px`,async({page,request})=>{
 const project=await(await request.post('/api/hardware/projects',{data:{name:'Actual breadboard',board:'arduino-uno'}})).json()
 for(const args of [{type:'led',id:'led',x:550,y:160},{type:'resistor',id:'r',properties:{value:'220'},x:460,y:120}])await request.post(`/api/hardware/project/${project.id}/command`,{data:{name:'add_component',args}})
 for(const [from,to] of [[{component:'board',pin:'13'},{component:'r',pin:'1'}],[{component:'r',pin:'2'},{component:'led',pin:'A'}],[{component:'led',pin:'C'},{component:'board',pin:'GND'}]])await request.post(`/api/hardware/project/${project.id}/command`,{data:{name:'connect_wire',args:{from,to}}})
 const initial=await(await request.get(`/api/hardware/projects/${project.id}`)).json()
 await page.setViewportSize({width,height:900});await page.goto(`/project/${project.id}`)
 const dots=page.locator('.hw-connected-pin-dot');await expect(dots).toHaveCount(2,{timeout:30000})
 await expect(dots.locator('title')).toContainText(['board · Pin 13','board · Pin GND.1'])
 await expect(page.locator('.hw-wires text')).toHaveCount(0)
 await page.getByRole('button',{name:'Select led',exact:true}).click();await expect(dots).toHaveCount(0)
 await page.getByRole('button',{name:'Select board',exact:true}).click();await expect(dots).toHaveCount(2)
 await page.getByRole('button',{name:'Use breadboard',exact:true}).click()
 await expect(page.locator('velxio-breadboard-mini')).toBeVisible({timeout:15000})
 const routed=await(await request.get(`/api/hardware/projects/${project.id}`)).json()
 const bb=routed.components.find((part:{type:string})=>part.type==='breadboard-mini')
 expect(bb).toBeTruthy();expect(routed.wires).toHaveLength(6)
 expect(routed.wires.every((wire:{from:{component:string};to:{component:string}})=>wire.from.component===bb.id||wire.to.component===bb.id)).toBe(true)
 expect(routed.firmware).toEqual(initial.firmware)
 await page.getByRole('button',{name:'Simulation',exact:true}).click()
 await page.getByRole('button',{name:'Undo last change',exact:true}).click()
 const restored=await(await request.get(`/api/hardware/projects/${project.id}`)).json()
 expect(restored.components).toEqual(initial.components);expect(restored.wires).toEqual(initial.wires)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})

test('board-only project does not offer breadboard insertion',async({page,request})=>{
 const project=await(await request.post('/api/hardware/projects',{data:{name:'Board only',board:'arduino-uno'}})).json()
 await page.goto(`/project/${project.id}`)
 await expect(page.getByLabel('Circuit canvas',{exact:true})).toBeVisible({timeout:30000})
 await expect(page.getByRole('button',{name:'Use breadboard',exact:true})).toBeDisabled()
})
